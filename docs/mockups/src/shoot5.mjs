import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const pw = require(`${execSync('npm root -g').toString().trim()}/playwright`);
const b = await pw.chromium.launch({ headless: true });
const page = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto(`file://${process.cwd()}/strategic.html`);
await page.waitForFunction('window.__done', null, { timeout: 60000 });
await (await page.$('canvas')).screenshot({ path: `${process.cwd()}/../proposal-war-strategic.png` });
console.log(errs.length ? errs : 'ok'); await b.close();
