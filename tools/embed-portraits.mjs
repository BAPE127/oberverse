// Embeds small portrait images from assets/portraits/*.jpg|png into
// src/content/portraits.js as data URIs, so portraits work in the standalone
// index.html (even when copied on its own). Run after adding a portrait:
//   node tools/embed-portraits.mjs && npm run build
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../assets/portraits/', import.meta.url);
const files = readdirSync(dir).filter((f) => /\.(jpe?g|png)$/i.test(f));
const lines = files.map((f) => {
  const id = f.replace(/\.(jpe?g|png)$/i, '');
  const mime = /png$/i.test(f) ? 'image/png' : 'image/jpeg';
  const b64 = readFileSync(new URL(f, dir)).toString('base64');
  return `  ${id}: 'data:${mime};base64,${b64}',`;
});
writeFileSync(
  new URL('../src/content/portraits.js', import.meta.url),
  `// GENERATED by tools/embed-portraits.mjs from assets/portraits/ — do not edit by hand.\n// Keep images small (≈224px square JPEG); originals live in assets/portraits/reference/.\nexport const PORTRAITS = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Embedded ${files.length} portrait(s): ${files.join(', ')}`);
